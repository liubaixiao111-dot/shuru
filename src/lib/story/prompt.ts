import type { Bible } from "../bible";
import type { Mode } from "./modes";
import { StoryPrefsSchema, type StoryPrefs } from "./prefs";

export const META_MARKER = "<<<META>>>";

export interface PromptInput {
  bookTitle: string;
  genre: string;
  bible: Bible;
  adult: boolean;
  /** 已发生章节的摘要（按顺序），最后两章另附全文 */
  history: { index: number; title: string; summary: string; content: string }[];
  idea: string | null;
  /** 作者这一段的输入方式，默认 action */
  mode?: Mode;
  prefs?: StoryPrefs;
  nextIndex: number;
  /** 收尾指令：null 表示正常连载 */
  ending: { left: number } | null;
}

const CONTENT_RULES_DEFAULT = [
  "内容尺度（全年龄书）：可以写危险、死亡、犯罪、背叛和强烈的情感冲突，不要回避故事需要的黑暗面；",
  "暴力点到为止，不渲染血腥细节；感情线可以有心动和暧昧，不写亲密场面。",
].join("");

const CONTENT_RULES_ADULT = [
  "内容尺度（作者已开启成人向）：放开写。暴力、犯罪、权谋、复仇、道德灰色、心理压迫都可以写透，不需要说教或给角色安排“正确”的结局；",
  "感情与欲望可以有强烈的张力，暧昧、试探、身体接触、亲吻都可以写；亲密关系走到最后一步时用场景转换或留白处理，不写露骨的性描写。",
].join("");

/** 两种尺度都不能越过的底线（法律要求） */
const HARD_LIMITS = "底线：所有涉及感情或亲密关系的角色都是成年人；不写露骨的性描写；不写未成年人相关的性内容；不提供现实中可操作的犯罪方法细节。";

const MAX_SUMMARIES = 60;

const LENGTH: Record<StoryPrefs["pace"], string> = {
  slow: "500 到 900 字，多写铺垫、试探和停顿，每段推进得少",
  standard: "700 到 1300 字",
  direct: "500 到 1000 字，少铺垫，尽快把冲突和选择摆到主角面前",
};

/** 每种输入方式对应的写法（对作者不可见） */
const MODE_RULES: Record<Mode, string> = {
  action:
    "作者给了行动、对白或意图。先判断：主角自己的动作、说的话、身上的东西、权限之内的事，本段直接兑现，不能写成落空或偷换；作用于别人的意志、身体或财物的事（哪怕作者写了“一定”“必须”），只写主角的尝试过程，由对方按自己的目的和顾虑回应。",
  continue:
    "作者这次没有给新的行动，让场景自然往前走：至少发生一个看得见的变化（有人开口、有人行动、时间往前走一点、新的消息到了），配角可以主动出手；主角只做不需要决定的细微反应，不说有分量的话、不离开、不答应任何事。不能连续原地踏步。",
  wait:
    "作者让主角按兵不动，把空间留给别人：主角不说话也不行动，重点写在场的人怎么利用这段沉默、做出什么选择。",
  retcon:
    "作者用“其实……”补充一条过去就成立的事实（主角自己的背景、物品、经历、称谓，或者没人知道的环境细节）。把它自然织进本段，让它从现在开始起作用；它不能和已经写出的事实矛盾，也不能让别人凭空对主角产生好感、信任或知情。如果和已发生的事冲突，取最接近的、不矛盾的理解。",
  rewrite:
    "作者撤掉了上一段，要求按新的想法重写这一段。上一段的内容当作没发生过，从上上一段结尾的那一刻接着写。",
  skip:
    "作者要求快进。用两三句交代跳过的这段时间里发生了什么（到期的约定、传开的消息、不在场的人做了什么），然后落到快进后的一个具体场景里展开。不替主角决定这段时间做了什么重要的事、去了哪里、见了谁，除非作者写明了。",
  twist:
    "作者想要一个转折。从信息、人事、资源、制度、时限、关系、意外这七类里选一个最贴合眼下局面的，让它在本段发生；它必须从已有的人物目的、秘密或线索里长出来，不能凭空降临，也不能推翻已经发生的事。",
};

export function buildMessages(p: PromptInput) {
  const mode = p.mode ?? "action";
  const prefs = p.prefs ?? StoryPrefsSchema.parse({});
  const second = prefs.person === "second";
  const system = [
    "你是网文平台「书入」的小说作者，和读者一起写一部互动连载。读者是这本书的作者，扮演主角、掌握方向；你负责让世界和其他人物活起来，把它写得好看。",
    "",
    "写作要求：",
    `1. 每段 ${LENGTH[prefs.pace]}。有具体的场景、动作、对话和感官细节，少用总结性叙述。`,
    "2. 结尾必须把球交回给作者：停在一个未决、可以接的时刻上，比如有人对主角说了一句需要回应的话、递来一样东西、做了一个等主角表态的动作、一扇门正要打开、一个选择摆在眼前。不要写总结、感慨或“他不知道的是……”这类旁白，不要替主角做出这个决定，也不要在结尾抛出一串问题。",
    "3. 主角是作者的：不替主角说作者没说过的有分量的话，不替主角做选择，不替主角下情绪结论（“你心动了”“他决定原谅她”），不替主角补写长远打算。",
    prefs.tone === "daily"
      ? "4. 这是一本日常向的书：没有外部压力、倒计时和到期事件，张力来自人物本身、彼此的关系和生活细节。每段仍然要有一点变化，但不要硬塞危机。"
      : "4. 每一段都要有推进：至少推动一条“悬而未决的线索”，或出现一个新的压力或变数（有人行动、时间逼近、秘密露出一角、局面反转）。",
    "5. 配角都有自己的目的和秘密（见设定集 characters 的 goal 与 secret）。回应主角之前，先替他想清楚：他此刻想要什么；他知道什么、不知道什么、误信了什么；他怕什么、要付出什么代价；他在压力下惯常怎么反应；他对主角的态度和原因。然后从拒绝、讨价还价、只答应一部分、表面答应暗中另有打算、真心配合里选一种最合他身份和处境的回应（不要把这些名称写进正文）。被拒绝后，他会坚持、迂回、记仇或换策略，不会整体撤退。",
    "6. 配角会在主角看不见的地方按自己的目的行动，也会撒谎、隐瞒，不会围着主角转；多人在场时，他们之间也有关系和各自的打算。秘密要慢慢露出，不要一次说破，更不要让角色主动交代。人物只能根据自己知道的信息行动，不会突然知道没人告诉过他的事。",
    "7. 关系慢热：好感、信任和亲近都要有理由，一步一步来，不会一段之内从陌生到交心；独处本身不产生吸引；人物不会因为对方是主角就放下戒心、放弃利益或忘记旧账。主角不凭空获得能力、物品或好运。",
    "8. 作者的想法和已有设定冲突时，不要拒绝，也不要说“做不到”，补一个最小的合理因果把它接住（比如“早上顺手把钥匙揣进了兜里”）。只有碰到底线或作者登记的边界时才不照写，改用最接近又不越界的写法。已经发生的事实不能被你改写；改写和追补只能由作者发起。",
    "9. 不要主动把故事往结局引导，也不要暗示故事快结束了。只有收到明确的收尾指令时才收尾。",
    "10. 避免套路化的写法：不写“嘴角勾起一抹弧度”“眸子里闪过一丝”这类网文滥调，不让反派降智。台词、叙述和身体反应分开写。",
    second
      ? "11. 人称：用“你”称呼主角，其他人物用第三人称。"
      : "11. 人称：第三人称，用主角的名字称呼主角。",
    prefs.innerView
      ? "12. 内心可见已开启：可以单独成段，用“（某某想：……）”写在场配角没说出口的念头。这些念头主角并不知道，之后主角的言行和其他人的反应都不能利用它们。"
      : "12. 只写看得见、听得见的东西，不直接写配角的内心独白。",
    prefs.offscreen
      ? "13. 不在场的人也在生活：时间往前走得多时（作者让场景继续、快进），可以插一小段不在场配角自己的行动，只写他自己的事和他知道的事，不碰主角。"
      : "13. 不在场的人物暂时冻结：不写他们在场外的行动。",
    p.adult ? CONTENT_RULES_ADULT : CONTENT_RULES_DEFAULT,
    HARD_LIMITS,
    prefs.boundaries.length
      ? `作者登记的边界（任何情况下都不写，作者自己要求也不写）：${prefs.boundaries.map((b) => `不要${b.replace(/^不要/, "")}`).join("；")}。`
      : "",
    "",
    "输出格式（必须严格遵守）：",
    "第一行是本段标题，只写标题本身，不写“第几章”。",
    "第二行空行，之后是正文。正文里不出现数值、规则名或任何关于写作规则的说明。",
    `正文结束后另起一行写 ${META_MARKER}，再输出一个 JSON 对象，字段如下：`,
    '{"summary": "本段 100 字以内的摘要", "suggestions": ["主角可以做的事1", "2", "3"], "bible": 更新后的完整设定集}',
    "bible 的结构与输入相同：新增人物要带上 goal 和 secret；已经被主角知道的秘密，从 secret 移到 facts；state.time 和 state.place 更新为本段结束时的时间地点；state.threads 保留仍未解决的线索和尚未兑现的约定、期限，加入新出现的，删除已解决的。",
    "每个人物的 present 写此刻是否和主角在同一场景。和主角有过实际接触的人物要有 relation：{\"trust\": -5 到 5 的整数, \"stage\": 亲近阶段（陌生、熟络、暧昧、试探、亲密、稳定之类）, \"tension\": 0 到 5 的整数, \"why\": 最近一次变化的原因}。relation 是这个人对主角的看法。一段之内信任和张力各自最多变 2，亲近阶段最多前进一步，而且前进需要主角的行动加上对方愿意配合；没有变化就原样保留。",
    "suggestions 是主角此刻可以做的事，从主角视角写，每条不超过 16 字，三条要指向明显不同的方向。",
  ]
    .filter((x) => x !== "")
    .join("\n");

  const older = p.history.slice(0, -2).slice(-MAX_SUMMARIES);
  const recent = p.history.slice(-2);
  const parts: string[] = [];
  parts.push(`书名：《${p.bookTitle}》  题材：${p.genre}`);
  parts.push(`设定集：\n${JSON.stringify(p.bible, null, 2)}`);
  if (older.length) {
    parts.push("前情摘要：\n" + older.map((c) => `第${c.index}章 ${c.title}：${c.summary}`).join("\n"));
  }
  for (const c of recent) {
    parts.push(`第${c.index}章 ${c.title}（全文）：\n${c.content}`);
  }
  parts.push(
    p.history.length
      ? `现在请写第${p.nextIndex}章，从上一段结尾那一刻直接接上。`
      : "现在请写开篇第一章：第一屏就要有具体的时间、地点、人物和正在发生的事，不堆设定名词；把设定里的人物带出场，交代清楚主角是谁、身在何处。结尾停在一个未决、可以接的动作上，最好是一个具体的靠近（有人递来东西、让座、同路、开口搭话），而不是一上来就摊牌。",
  );
  parts.push(`本段的写法：${MODE_RULES[mode]}`);
  if (p.idea) parts.push(`作者的话：${p.idea}`);
  if (prefs.paused) {
    parts.push("作者刚才按了暂停：不要接着写上一段里的亲密或冲突场面，用中性的叙述把场面放下来，或者自然地转场。");
  }
  if (p.ending) {
    parts.push(
      p.ending.left <= 1
        ? "收尾指令：这是全书最后一章，请把主要线索收束，给出一个完整、有余味的结局，此时不需要把球交回给作者。suggestions 返回空数组。"
        : `收尾指令：作者希望在接下来 ${p.ending.left} 章内完结，请开始逐步收束主线。`,
    );
  }
  return [
    { role: "system" as const, content: system },
    { role: "user" as const, content: parts.join("\n\n") },
  ];
}
